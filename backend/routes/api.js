import { Router } from 'express';
import { authenticate, allow } from '../middleware/auth.js';
import { login, loginValidation, me, exchangeSession, logout } from '../controllers/authController.js';
import { getState } from '../controllers/stateController.js';
import { listTables, createTable, updateTable, listMenu, createMenuItem, updateMenuItem, getSettings, updateSettings, listUsers, createUser, updateUser, createOrder, listOrders, updateOrderStatus, addOrderItems, updateBillDiscount, updateBillStatus, recordPayment, getReports, listBills, listPayments, listAuditEvents, listNotifications, health } from '../controllers/domainController.js';
import { listKots, updateKotStatus } from '../controllers/kotController.js';
import { assignWaiter, markNotificationRead, cancelKotItem } from '../controllers/operationsController.js';
import { importBrowserState } from '../controllers/migrationController.js';
import { listResettableStaff, resetStaffPassword } from '../controllers/staffController.js';
import assistantRouter from './assistant.js';

const router = Router();
router.post('/auth/login', loginValidation, login);
router.get('/auth/me', authenticate, me);
router.post('/auth/session', authenticate, exchangeSession);
router.post('/auth/logout', authenticate, logout);
router.get('/state', authenticate, getState);
router.post('/migration/browser-state', authenticate, importBrowserState);
router.use('/assistant', assistantRouter);
router.get('/users', authenticate, allow('waiters:manage'), listUsers);
router.get('/staff/password-reset', authenticate, allow('waiters:manage'), listResettableStaff);
router.patch('/users/:id/password', authenticate, allow('waiters:manage'), resetStaffPassword);
router.post('/users', authenticate, allow('waiters:manage'), createUser);
router.patch('/users/:id', authenticate, allow('waiters:manage'), updateUser);
router.get('/payments', authenticate, allow('billing:view'), listPayments);
router.get('/audit-events', authenticate, allow('audit:view'), listAuditEvents);
router.get('/notifications', authenticate, allow('notifications:own','notifications:manage'), listNotifications);
router.get('/tables', authenticate, allow('tables:view'), listTables);
router.post('/tables', authenticate, allow('tables:manage'), createTable);
router.patch('/tables/:id', authenticate, allow('tables:manage'), updateTable);
router.get('/menu', authenticate, allow('menu:view'), listMenu);
router.post('/menu', authenticate, allow('menu:manage'), createMenuItem);
router.patch('/menu/:id', authenticate, allow('menu:manage'), updateMenuItem);
router.get('/settings', authenticate, allow('settings:limited','settings:full'), getSettings);
router.patch('/settings', authenticate, allow('settings:limited','settings:full'), updateSettings);
router.get('/orders', authenticate, allow('orders:view','kitchen:view'), listOrders);
router.post('/orders', authenticate, allow('orders:create'), createOrder);
router.post('/orders/:id/items', authenticate, allow('orders:addItems'), addOrderItems);
router.patch('/orders/:id/status', authenticate, allow('orders:manage'), updateOrderStatus);
router.patch('/orders/:id/assignment', authenticate, allow('waiters:manage'), assignWaiter);
router.post('/kots/:kotId/items/:lineId/cancellations', authenticate, allow('kitchen:cancel'), cancelKotItem);
router.patch('/notifications/:id/read', authenticate, allow('notifications:own','notifications:manage'), markNotificationRead);
router.get('/kots', authenticate, allow('kitchen:view'), listKots);
router.patch('/kots/:id/status', authenticate, allow('kitchen:update','kitchen:serve'), updateKotStatus);
router.get('/billing', authenticate, allow('billing:view'), listBills);
router.patch('/billing/:orderId/discount', authenticate, allow('billing:manage'), updateBillDiscount);
router.patch('/billing/:orderId/status', authenticate, allow('billing:manage'), updateBillStatus);
router.post('/billing/:orderId/payments', authenticate, allow('billing:manage'), recordPayment);
router.get('/reports/summary', authenticate, allow('reports:limited','reports:full'), getReports);
router.get('/health', health);
export default router;
